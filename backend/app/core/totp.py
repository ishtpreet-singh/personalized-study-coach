"""
TOTP (Time-Based One-Time Password) Utilities — Phase 1.5

Provides:
  - generate_totp_secret()        — Creates a new cryptographically random base32 secret
  - get_totp_uri(secret, email)   — Builds the otpauth:// URI for QR code provisioning
  - generate_qr_code_base64(uri)  — Returns a base64 data-URI string for inline <img> embedding
  - verify_totp(secret, code)     — Validates a 6-digit OTP code (±1 window tolerance)

The ±1 window tolerance in verify_totp accounts for clock drift between the
user's device and the server — standard practice for TOTP implementations.
"""

import base64
import io
import logging

import pyotp
import qrcode

logger = logging.getLogger(__name__)

# ── App name shown in authenticator apps ────────────────────────
TOTP_ISSUER = "Personalized Study Coach"


def generate_totp_secret() -> str:
    """
    Generate a new cryptographically random base32 TOTP secret.

    Returns:
        A 32-character base32-encoded string suitable for pyotp.TOTP.
    """
    return pyotp.random_base32()


def get_totp_uri(secret: str, email: str) -> str:
    """
    Build the otpauth:// provisioning URI for QR code generation.

    This URI format is understood by all major authenticator apps
    (Google Authenticator, Authy, Microsoft Authenticator, etc.).

    Args:
        secret: The base32 TOTP secret generated by generate_totp_secret().
        email: The user's email — used as the account identifier in the app.

    Returns:
        An otpauth://totp/... URI string.
    """
    totp = pyotp.TOTP(secret)
    return totp.provisioning_uri(name=email, issuer_name=TOTP_ISSUER)


def generate_qr_code_base64(uri: str) -> str:
    """
    Render the TOTP provisioning URI as a base64-encoded PNG data URI.

    The returned string can be used directly as the `src` attribute of an
    <img> tag without any additional HTTP requests:
      <img src="data:image/png;base64,iVBOR..." />

    Args:
        uri: The otpauth:// URI from get_totp_uri().

    Returns:
        A data URI string: "data:image/png;base64,<encoded_bytes>"
    """
    qr = qrcode.QRCode(
        version=1,
        error_correction=qrcode.constants.ERROR_CORRECT_L,
        box_size=10,
        border=4,
    )
    qr.add_data(uri)
    qr.make(fit=True)

    img = qr.make_image(fill_color="black", back_color="white")

    buffer = io.BytesIO()
    img.save(buffer, format="PNG")
    buffer.seek(0)

    encoded = base64.b64encode(buffer.read()).decode("utf-8")
    return f"data:image/png;base64,{encoded}"


def verify_totp(secret: str, code: str) -> bool:
    """
    Verify a 6-digit TOTP code against the given secret.

    Uses a ±1 window (valid_window=1) which allows codes from the previous
    and next 30-second windows. This is the standard tolerance for clock drift
    between servers and mobile devices.

    Args:
        secret: The user's stored base32 TOTP secret.
        code: The 6-digit code entered by the user (string, may include spaces).

    Returns:
        True if the code is valid, False otherwise.
    """
    # Strip spaces/dashes in case user copies with separators
    code = code.replace(" ", "").replace("-", "").strip()

    try:
        totp = pyotp.TOTP(secret)
        return totp.verify(code, valid_window=1)
    except Exception as exc:
        logger.warning(f"TOTP verification error: {exc}")
        return False
